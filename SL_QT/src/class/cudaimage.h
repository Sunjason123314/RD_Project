#ifndef checkCudaErrors
#define checkCudaErrors(expr)                                                        \
    do {                                                                             \
        cudaError_t _err = (expr);                                                   \
        if (_err != cudaSuccess) {                                                   \
            std::cerr << "CUDA error: " << cudaGetErrorString(_err)                \
                      << " (" << static_cast<int>(_err) << ") at "                 \
                      << __FILE__ << ":" << __LINE__ << std::endl;                 \
        }                                                                            \
    } while (0)
#endif

